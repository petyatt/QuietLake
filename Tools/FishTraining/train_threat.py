"""Fit the expected value of a short response to a perceived threat in the prototype.
Inputs are cue strength, current/predicted separation (scaled by 6 m), shelter
at the endpoint, movement effort and energy. Units and costs are game assumptions.
"""
import math
import random
from pathlib import Path


def rollout(x):
    signal, before, after, cover, effort, energy = x
    # Expected loss is sampled at intermediate positions along the escape path.
    loss = 0
    for step in range(1, 5):
        t = step / 4
        separation = before + (after-before)*t
        hazard = signal * (1-separation)**2 * (1-cover*t*.8)
        loss += hazard/4
    return -loss - effort * (.035 + .055*(1-energy))


def predict(x, hidden, output):
    h = [math.tanh(sum(a*b for a,b in zip(row,x)) + row[-1]) for row in hidden]
    return h, sum(a*b for a,b in zip(output,h)) + output[-1]


def train():
    rng = random.Random(619)
    hidden = [[rng.uniform(-.6,.6) for _ in range(7)] for _ in range(16)]
    output = [rng.uniform(-.2,.2) for _ in range(17)]
    for i in range(85000):
        x = [rng.random() for _ in range(6)]
        if i % 5 == 0: x[0] = 0.0
        h, y = predict(x,hidden,output)
        error = .025/(1+i/20000)*(rollout(x)-y)
        for j,row in enumerate(hidden):
            d = error * output[j] * (1-h[j]**2)
            for k,v in enumerate(x+[1]): row[k] += d*v
        for k,v in enumerate(h+[1]): output[k] += error*v
    return hidden,output


if __name__ == "__main__":
    h,o = train()
    def score(x): return predict(x,h,o)[1]
    assert score([.95,.15,.62,.2,1,.8]) > score([.95,.15,.15,.2,0,.8])
    assert score([0,.15,.15,.2,0,.8]) > score([0,.15,.62,.2,1,.8])
    assert score([.9,.15,.5,1,.7,.7]) > score([.9,.15,.5,0,.7,.7])
    lines = ["// Generated by Tools/FishTraining/train_threat.py", "#pragma once",
             "namespace ThreatPolicy {", "constexpr double Hidden[16][7] = {"]
    lines.extend("    {" + ", ".join(map(repr,row)) + "}," for row in h)
    lines += ["};","constexpr double Output[17] = {" + ", ".join(map(repr,o)) + "};","}"]
    (Path(__file__).resolve().parents[2]/"Source/QuietLake/ThreatPolicyWeights.h").write_text("\n".join(lines)+"\n")
