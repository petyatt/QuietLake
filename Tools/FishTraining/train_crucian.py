"""Crucian carp patch values in the prototype. Coefficients are game assumptions."""
from pathlib import Path

from train_species import PROFILES, bout, fit, validate


def outcome(x, action, rng):
    env = x[:6]
    bottom_access, benthos = x[6:]
    risk, cover = env[3:5]
    # A sheltered substrate patch can supply benthos only within reach.
    if action == 1:
        env[5] *= 1 - benthos * (1 - bottom_access)
    value = bout(env, action, PROFILES["Crucian"], rng)
    if action == 1:
        value += .48 * bottom_access * benthos * env[5] * env[0]
        value -= .65 * risk * (1 - cover)
    else:
        value += .30 * risk * cover
    return value


if __name__ == "__main__":
    weights = fit(PROFILES["Crucian"], 788, inputs=8, simulator=outcome)
    hits = validate(PROFILES["Crucian"], weights, inputs=8, simulator=outcome)
    if hits < 190:
        raise RuntimeError(f"Only {hits}/250 decisions agree with held-out simulated returns")
    print(f"Crucian: {hits}/250 held-out decisions")
    lines = ["// Generated by Tools/FishTraining/train_crucian.py", "#pragma once", "namespace CrucianPatch {"]
    for name, matrix in zip(("Hidden", "Output"), weights):
        lines.append(f"constexpr double {name}[{len(matrix)}][{len(matrix[0])}] = {{")
        lines.extend("    {" + ", ".join(map(repr, row)) + "}," for row in matrix)
        lines.append("};")
    lines.append("}")
    (Path(__file__).resolve().parents[2] / "Source/QuietLake/CrucianPatchWeights.h").write_text("\n".join(lines) + "\n")
