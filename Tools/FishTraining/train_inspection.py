"""Train the value of approaching for information before tasting a visible morsel."""
from pathlib import Path
import random
import re

from train_threat import predict

root = Path(__file__).resolve().parents[2] / "Source/QuietLake"
rows = re.findall(r"\{([-+\d.eE, ]+)\}", (root/"FishingPolicyWeights.h").read_text())
hidden, output = [[float(v) for v in row.split(",")] for row in rows[:-1]], list(map(float, rows[-1].split(",")))
rng = random.Random(180)
for i in range(100000):
    cue, appeal, hunger, risk, memory, proximity = x = [rng.random() for _ in range(6)]
    # Close inspection resolves uncertainty about food; an unsuccessful visit costs travel and exposure.
    benefit = (cue**.5) * appeal * hunger * (1 + proximity)
    target = benefit - .32 - .3*(1-proximity) - .8*risk - .55*memory
    h, val = predict(x, hidden, output)
    err = .035/(1+i/50000)*(target-val)
    for j,row in enumerate(hidden):
        delta = err*output[j]*(1-h[j]**2)
        for k,v in enumerate(x+[1.]): row[k] += delta*v
    for j,v in enumerate(h+[1.]): output[j] += err*v
assert predict([.7,.9,.9,0,0,.8],hidden,output)[1] > 0 > predict([.1,.4,.2,.8,0,.3],hidden,output)[1]
lines = ["// Generated by train_inspection.py", "#pragma once", "namespace Inspection {", "constexpr double Hidden[16][7] = {"]
lines.extend("    {" + ", ".join(map(repr,r)) + "}," for r in hidden)
lines += ["};","constexpr double Output[17] = {" + ", ".join(map(repr,output)) + "};","}"]
(root/"InspectionWeights.h").write_text("\n".join(lines)+"\n")
