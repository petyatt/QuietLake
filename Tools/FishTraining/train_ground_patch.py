"""Fit the extra value of a concentrated patch over a short simulated feeding bout."""
from pathlib import Path
import math
import random

from train_threat import predict


def train():
    rng = random.Random(728)
    hidden = [[rng.uniform(-.5, .5) for _ in range(7)] for _ in range(16)]
    output = [rng.uniform(-.2, .2) for _ in range(17)]
    for step in range(140000):
        scent, portion, hunger, risk, alternative, appeal = x = [rng.random() for _ in range(6)]
        if step % 4 == 0:
            x[0] = scent = scent * .4
        # Chance of finding the patch from its scent; concentrated food allows repeated meals.
        found = 1 - math.exp(-6*scent)
        benefit = found * min(hunger, portion) * appeal * (1-risk)
        target = 2.4 * benefit - .30 * alternative * hunger - .12 * (1-found)
        h, value = predict(x, hidden, output)
        e = .035 / (1 + step / 60000) * (target-value)
        for j, row in enumerate(hidden):
            d = e * output[j] * (1-h[j]**2)
            for k, v in enumerate(x+[1.]): row[k] += d*v
        for j, v in enumerate(h+[1.]): output[j] += e*v
    def value(x): return predict(x, hidden, output)[1]
    assert value([.3,.9,.8,.02,.1,1]) > value([.3,.9,.8,.02,.9,1]) > value([.01,.05,.8,.6,.9,1])
    rows = ["// Generated by train_ground_patch.py", "#pragma once", "namespace GroundPatch {",
            "constexpr double Hidden[16][7] = {"]
    rows.extend("    {" + ", ".join(map(repr,row)) + "}," for row in hidden)
    rows += ["};","constexpr double Output[17] = {" + ", ".join(map(repr,output)) + "};","}"]
    (Path(__file__).resolve().parents[2]/"Source/QuietLake/GroundPatchWeights.h").write_text("\n".join(rows)+"\n")


if __name__ == "__main__":
    train()
