"""Fit species-specific values of cruise, forage and rest from simulated bouts.
Inputs: hunger, reserves, activity, threat, cover, local food. Units normalised.
Coefficients are game assumptions; observations in these bouts are synthetic.
"""
import math
import random
from pathlib import Path

# Exposure, shelter benefit and mobility while foraging.
PROFILES = {"Perch": (.6,.4,.65), "Roach": (.95,.35,.8),
            "Crucian": (.85,.85,.3), "Pike": (.45,.8,.25),
            "Bream": (.75,.45,.45), "Bleak": (1,.25,.95), "Rudd": (.85,.75,.6)}


def bout(x, action, profile, rng):
    hunger, energy, activity, risk, cover, food = x
    exposure, shelter, mobility = profile
    score = 0
    for _ in range(6):
        meal = 0
        effort = (.025, .035, .004)[action]
        if action == 1:
            chance = food * activity * (.5 + .5*(mobility + (1-mobility)*cover))
            meal = min(.16, hunger) if rng.random() < chance else 0
        if action == 0:
            food += .18*(1-food)
            risk *= .82
        if action == 2:
            energy = min(1, energy+.028)
        score += meal * (1+2*hunger) - effort * (1.5-energy)
        score -= .13*risk*exposure*(1-cover*shelter)*(.65,1.3,.35)[action]
        score -= .08*max(0,.45-energy)
        hunger = min(1,max(0,hunger+.012-meal))
        energy = max(0,energy-effort)
    # Value of replenished reserves and an improved feeding patch after the bout.
    return score + (energy-x[1])*(1.7-1.6*x[1]) + (food-x[5])*hunger*.38


def infer(x, hidden, output):
    h = [math.tanh(sum(a*b for a,b in zip(row,x))+row[-1]) for row in hidden]
    y = [sum(a*b for a,b in zip(row,h))+row[-1] for row in output]
    return h,y


def fit(profile, seed, inputs=6, simulator=None):
    simulate = simulator or (lambda x, a, rng: bout(x, a, profile, rng))
    rng=random.Random(seed)
    hidden=[[rng.uniform(-.6,.6) for _ in range(inputs+1)] for _ in range(12)]
    output=[[rng.uniform(-.2,.2) for _ in range(13)] for _ in range(3)]
    for i in range(14000):
        x=[rng.random() for _ in range(inputs)]
        target=[simulate(x,a,rng) for a in range(3)]
        h,y=infer(x,hidden,output)
        errors=[(.022/(1+i/10000))*(t-v) for t,v in zip(target,y)]
        for j,row in enumerate(hidden):
            delta=(1-h[j]**2)*sum(e*w[j] for e,w in zip(errors,output))
            for k,v in enumerate(x+[1]): row[k]+=delta*v
        for e,row in zip(errors,output):
            for k,v in enumerate(h+[1]): row[k]+=e*v
    return hidden,output


def validate(profile, weights, inputs=6, simulator=None):
    simulate = simulator or (lambda x, a, rng: bout(x, a, profile, rng))
    rng=random.Random(71238)
    hits=0
    for i in range(250):
        x=[rng.random() for _ in range(inputs)]
        reference=[sum(simulate(x,a,rng) for _ in range(50)) for a in range(3)]
        _,prediction=infer(x,*weights)
        hits+=max(range(3),key=reference.__getitem__)==max(range(3),key=prediction.__getitem__)
    return hits


if __name__=="__main__":
    lines=["// Generated by Tools/FishTraining/train_species.py", "#pragma once", "namespace FishDecisions {"]
    for i,(species,profile) in enumerate(PROFILES.items()):
        weights=fit(profile,786+i)
        hits=validate(profile,weights)
        print(species,hits,"/ 250 held-out simulated choices",flush=True)
        if hits<190: raise RuntimeError("Low agreement with simulated returns")
        for name,m in zip(("Hidden","Output"),weights):
            lines.append(f"constexpr double {species}{name}[{len(m)}][{len(m[0])}] = {{")
            lines.extend("    {"+", ".join(map(repr,row))+"}," for row in m)
            lines.append("};")
    lines.append("}")
    (Path(__file__).resolve().parents[2]/"Source/QuietLake/FishDecisionWeights.h").write_text("\n".join(lines)+"\n")
