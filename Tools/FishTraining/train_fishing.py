"""Fit encounter values on synthetic fishing scenarios. Costs are prototype assumptions."""
from pathlib import Path
import random

from train_threat import predict


def train():
    rng = random.Random(914)
    hidden = [[rng.uniform(-.5, .5) for _ in range(7)] for _ in range(16)]
    output = [rng.uniform(-.2, .2) for _ in range(17)]
    for step in range(100000):
        cue, appeal, hunger, risk, memory, samples = x = [rng.random() for _ in range(6)]
        gain = cue * appeal * (.25 + hunger) * (1 + .4 * samples)
        cost = .07 + .45*risk + .22*memory + .1*(1-samples)
        activations, value = predict(x, hidden, output)
        error = .035 / (1 + step/50000) * (gain-cost-value)
        for j, row in enumerate(hidden):
            delta = error * output[j] * (1-activations[j]**2)
            for i, feature in enumerate(x+[1.]): row[i] += delta*feature
        for i, feature in enumerate(activations+[1.]): output[i] += error*feature
    score = lambda x: predict(x, hidden, output)[1]
    assert score([1,.9,.9,0,0,1]) > .4
    assert score([1,.05,.2,.8,.7,1]) < 0
    assert score([.1,.7,.5,.7,.5,0]) < 0
    rows = ["// Generated by train_fishing.py", "#pragma once", "namespace FishingPolicy {",
            "constexpr double Hidden[16][7] = {"]
    rows.extend("    {" + ", ".join(map(repr, row)) + "}," for row in hidden)
    rows += ["};", "constexpr double Output[17] = {" + ", ".join(map(repr, output)) + "};", "}"]
    path = Path(__file__).resolve().parents[2] / "Source/QuietLake/FishingPolicyWeights.h"
    path.write_text("\n".join(rows)+"\n")


if __name__ == "__main__":
    train()
