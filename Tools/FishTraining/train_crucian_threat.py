"""Fine-tune the shared escape network for crucian using simulated encounter costs."""
import math
import random
import re
from pathlib import Path

from train_threat import predict

SOURCE = Path(__file__).resolve().parents[2] / "Source/QuietLake"


def train(bed=False):
    original = (SOURCE / ("CrucianThreatWeights.h" if bed else "ThreatPolicyWeights.h")).read_text()
    rows = re.findall(r"\{([-+\d.eE, ]+)\}", original)
    hidden, output = [[float(v) for v in row.split(",")] for row in rows[:-1]], [
        float(v) for v in rows[-1].split(",")]
    rng = random.Random(625)
    for step in range(160000):
        signal, before, after, cover, effort, energy = (rng.random() for _ in range(6))
        if step % 3 == 0:
            effort, after = 0., before
        if step % 4 == 0:
            signal *= .3
        x = [signal, before, after, cover, effort, energy]
        # In exposed water, remaining near a detected predator prolongs exposure.
        # Dense plants instead reward immobility, which movement compromises.
        risk = math.sqrt(signal) * (1-after)**2
        concealment = cover**2 * (1 - .65*effort)
        target = -risk * (1 - .97*concealment) - effort*(.009 + .018*(1-energy))
        if bed:
            # Exposure continues after a dash that ends outside the plant canopy.
            target += math.sqrt(signal) * cover * (.85 - .25 * effort)
        h, value = predict(x, hidden, output)
        error = .035 / (1 + step/70000) * (target-value)
        for j, row in enumerate(hidden):
            delta = error * output[j] * (1-h[j]**2)
            for k, v in enumerate(x+[1.]): row[k] += delta*v
        for j, v in enumerate(h+[1.]): output[j] += error*v
    def value(after, cover, effort):
        return predict([.3,.2,after,cover,effort,.7], hidden, output)[1]
    assert value(.55,.1,.9) > value(.2,.1,0)
    assert value(.2,1,0) > value(.55,.1,.9)
    lines = ["// Generated by train_crucian_threat.py", "#pragma once",
             ("namespace CrucianBedThreat {" if bed else "namespace CrucianThreat {"), "constexpr double Hidden[16][7] = {"]
    lines.extend("    {" + ", ".join(map(repr,row)) + "}," for row in hidden)
    lines += ["};","constexpr double Output[17] = {" + ", ".join(map(repr,output)) + "};","}"]
    (SOURCE / ("CrucianBedThreatWeights.h" if bed else "CrucianThreatWeights.h")).write_text("\n".join(lines)+"\n")


if __name__ == "__main__":
    train()
    train(bed=True)
