"""Export the trained encounter policy as read-only C++ weights."""
import json
from pathlib import Path

from pike_env import ACTIONS, FEATURES

root = Path(__file__).resolve().parent
model = json.loads((root / "pike_policy.json").read_text())
assert model["version"] == 1 and model["actions"] == list(ACTIONS) and model["features"] == list(FEATURES)
lines = ["// Generated by Tools/FishTraining/export_pike.py", "#pragma once", "namespace PikeWeights", "{"]
for key, rows, cols in [("hidden", 12, 6), ("output", 4, 13)]:
    matrix = model[key]
    assert len(matrix) == rows and all(len(row) == cols for row in matrix)
    lines.append(f"constexpr double {key.title()}[{rows}][{cols}] = {{")
    for row in matrix:
        lines.append("    {" + ", ".join(map(repr, row)) + "},")
    lines.append("};")
lines.append("}")
(root.parents[1] / "Source/QuietLake/PikeWeights.h").write_text("\n".join(lines) + "\n")
