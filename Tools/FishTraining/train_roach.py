"""Estimate returns for roach feeding patches, including nearby shoal mates.
The three extra inputs encode spacing, local density and alignment with moving mates.
"""
# Training uses the deterministic generator supplied by train_species.
from pathlib import Path
from train_species import bout, PROFILES


def outcome(x, action, rng):
    spacing, density, alignment = x[6:]
    social = spacing * (.45 + .55 * density)
    env = x[:6]
    env[3] *= 1 - .55 * social
    # Neighbours help locate a patch but crowded fish compete for each meal.
    env[5] = min(1, env[5] * (1 + .22 * social) / (1 + .25 * density**2))
    value = bout(env, action, PROFILES["Roach"], rng)
    return value + social * (.19 + .65*x[3]) + .06 * alignment * social


if __name__ == "__main__":
    from train_species import fit, validate
    weights = fit(PROFILES["Roach"], 787, inputs=9, simulator=outcome)
    hits = validate(PROFILES["Roach"], weights, inputs=9, simulator=outcome)
    print("Roach social decisions:", hits, "/ 250 held-out")
    if hits < 190:
        raise RuntimeError("Insufficient held-out agreement")
    lines = ["// Generated by Tools/FishTraining/train_roach.py", "#pragma once", "namespace RoachShoal {"]
    for label, matrix in zip(("Hidden","Output"), weights):
        lines.append(f"constexpr double {label}[{len(matrix)}][{len(matrix[0])}] = {{")
        lines.extend("    {" + ", ".join(map(repr,row)) + "}," for row in matrix)
        lines.append("};")
    lines.append("}")
    (Path(__file__).resolve().parents[2]/"Source/QuietLake/RoachShoalWeights.h").write_text("\n".join(lines)+"\n")
