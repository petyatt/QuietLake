"""Fine-tune fishing weights for one morsel versus another mouthful at a known patch."""
from pathlib import Path
import random
import re

from train_threat import predict

source = Path(__file__).resolve().parents[2] / "Source/QuietLake"


def train():
    rows = re.findall(r"\{([-+\d.eE, ]+)\}", (source / "FishingPolicyWeights.h").read_text())
    hidden, output = [[float(v) for v in r.split(",")] for r in rows[:-1]], list(map(float, rows[-1].split(",")))
    rng = random.Random(819)
    for i in range(120000):
        cue, appeal, hunger, risk, portion, familiarity = x = [rng.random() for _ in range(6)]
        # Both choices leave the patch available. Compare only this feeding opportunity.
        morsel = cue * appeal * (.35 + hunger) * (.8 + .45*familiarity)
        loose = (.16 + .48*portion) * (.55 + hunger)
        target = morsel - loose - .6*risk
        h, value = predict(x, hidden, output)
        error = .03/(1+i/60000) * (target-value)
        for j, row in enumerate(hidden):
            d = error*output[j]*(1-h[j]**2)
            for k, v in enumerate(x+[1.]): row[k] += d*v
        for j, v in enumerate(h+[1.]): output[j] += error*v
    score = lambda x: predict(x, hidden, output)[1]
    assert score([.95,.95,.7,.01,.25,.8]) > 0 > score([.1,.3,.4,.8,.95,.2])
    assert score([.7,.8,.6,.1,.2,.6]) > score([.7,.8,.6,.1,.9,.6])
    lines = ["// Generated by train_patch_morsel.py", "#pragma once", "namespace PatchMorsel {",
             "constexpr double Hidden[16][7] = {"]
    lines.extend("    {" + ", ".join(map(repr,r)) + "}," for r in hidden)
    lines += ["};","constexpr double Output[17] = {" + ", ".join(map(repr,output)) + "};","}"]
    (source/"PatchMorselWeights.h").write_text("\n".join(lines)+"\n")


if __name__ == "__main__":
    train()
