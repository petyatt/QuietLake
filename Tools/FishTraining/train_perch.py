"""Train the prototype perch to pursue mobile fry while exposed to a larger predator."""
import json
from pathlib import Path

from pike_env import Encounter
from train_pike import evaluate, forward, train


class PerchEncounter(Encounter):
    def step(self, action):
        # Fry swim ahead during pursuit. Exposure to the pike is costlier in open water.
        exposure = self.danger * (1 - self.cover)
        if action == 1:
            self.distance = min(8, self.distance + .32)
        reward, done, caught, cost = super().step(action)
        if action in (1, 2):
            reward -= .38 * exposure
        return reward, done, caught, cost


def policy(model):
    def choose(x):
        _, values = forward(model, x)
        return max(range(len(values)), key=values.__getitem__)
    return choose


if __name__ == "__main__":
    root = Path(__file__).resolve().parent
    old = json.loads((root / "pike_policy.json").read_text())
    perch = train(18000, 791, PerchEncounter)
    for name, model in (("previous", old), ("perch", perch)):
        print(name, evaluate(policy(model), 500, PerchEncounter))
    lines = ["// Generated by Tools/FishTraining/train_perch.py", "#pragma once", "namespace PerchHunt {"]
    for key in ("hidden", "output"):
        rows = perch[key]
        lines.append(f"constexpr double {key.title()}[{len(rows)}][{len(rows[0])}] = {{")
        lines.extend("    {" + ", ".join(map(repr, row)) + "}," for row in rows)
        lines.append("};")
    lines.append("}")
    (root.parents[1] / "Source/QuietLake/PerchHuntWeights.h").write_text("\n".join(lines) + "\n")
